#!/usr/bin/env node
/**
 * Extracts the design token inventory from the mirrored build's CSS and
 * writes mirror-overlay/design-tokens.json (the editor's default seed).
 *
 * Usage: node tools/extract-tokens.mjs
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, "..", "mirror");
const OUT = path.join(HERE, "..", "mirror-overlay", "design-tokens.json");

const css = await readFile(path.join(ROOT, "_next/static/chunks/1-2akml8d4gu7.css"), "utf8");

const blockRe = /([^{}]{1,220})\{([^{}]+)\}/g;
const blocks = [];
let m;
while ((m = blockRe.exec(css))) {
  const vars = m[2].match(/--[a-zA-Z0-9-]+:[^;]+/g);
  if (vars) blocks.push([m[1].trim().replace(/\s+/g, " "), vars]);
}

// Merge var lists for a selector predicate, later blocks win.
function collect(pred) {
  const out = {};
  for (const [sel, vars] of blocks) {
    if (!pred(sel)) continue;
    for (const v of vars) {
      const i = v.indexOf(":");
      out[v.slice(0, i).trim()] = v.slice(i + 1).trim();
    }
  }
  return out;
}

const isRoot = (s) => s.startsWith(":root") || s.startsWith(":host");
const isDarkScope = (s) => s.startsWith(":root,[data-theme=dark]") && !s.includes("data-scheme");
const isLightScope = (s) => s.startsWith("[data-theme=light]") && !s.includes("data-scheme");
// Plain :root blocks (shadcn alias layer, --radius) are theme-independent too.
const isPlainRoot = (s) => s === ":root";

// Palette primitives: only from non-scheme-scoped blocks (base ramps).
const paletteAll = collect((s) => (isRoot(s) || isDarkScope(s) || isLightScope(s)) && !s.includes("data-scheme"));
const palette = {};
for (const [k, v] of Object.entries(paletteAll)) if (k.startsWith("--color-")) palette[k] = v;

const resolve = (v, depth = 0) => {
  if (depth > 6) return v;
  const mm = v.match(/^var\(\s*(--[a-zA-Z0-9-]+)\s*(?:,\s*([^)]+))?\)$/);
  if (!mm) return v;
  const val = palette[mm[1]] ?? globalAll[mm[1]] ?? darkAll[mm[1]] ?? lightAll[mm[1]];
  return val !== undefined ? resolve(val, depth + 1) : (mm[2] ? mm[2].trim() : v);
};

// Semantic tokens live on :root,[data-theme=dark] (dark/default) and
// [data-theme=light] (light overrides).
const darkAll = collect(isDarkScope);
const lightAll = collect(isLightScope);
const globalAll = collect((s) => s.startsWith(":root,:host"));
const plainRoot = collect(isPlainRoot);

const SEMANTIC_RE = /^--(bg|text|border|icon|cat)-[a-z0-9-]+$/;
const TYPO_RE = /^--(text-|leading-|font-(sans|mono|heading|regular|semibold|bold|black))/;
const SPACE_RE = /^--(spacing|space-|page-gutter|container-(narrow|wide)|grid-)/;
const RADIUS_RE = /^--radius/;
const SIZE_RE = /^--size-/;
const ALIAS_RE = /^--(background|foreground|card|popover|primary|secondary|muted|accent|destructive|input|ring|chart|sidebar|bnav-|on-dark-|button-primary)/;

function pick(all, res) {
  const out = {};
  for (const [k, v] of Object.entries(all)) if (res.test(k)) out[k] = resolve(v);
  return out;
}

const store = {
  _meta: {
    source: "mirror/_next/static/chunks/1-2akml8d4gu7.css",
    note: "Generated by tools/extract-tokens.mjs. Used as fallback seed by the Design System Editor.",
  },
  global: {
    ...pick(darkAll, TYPO_RE),
    ...pick(darkAll, SPACE_RE),
    ...pick(darkAll, RADIUS_RE),
    ...pick(darkAll, SIZE_RE),
    ...pick(darkAll, ALIAS_RE),
    ...pick({ ...plainRoot, ...globalAll }, /^(--spacing|--radius|--text-|--font-weight-|--tracking-|--leading-(tight|snug|relaxed)|--container-|--default-transition-duration)$/),
  },
  dark: pick(darkAll, SEMANTIC_RE),
  light: pick(lightAll, SEMANTIC_RE),
  palette,
};

await mkdir(path.dirname(OUT), { recursive: true });
await writeFile(OUT, JSON.stringify(store, null, 2) + "\n");
const count = (o) => Object.keys(o).length;
console.log(
  `design-tokens.json: global=${count(store.global)} dark=${count(store.dark)} light=${count(store.light)} palette=${count(store.palette)}`
);
